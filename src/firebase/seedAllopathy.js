export async function seedAllopathy(force = false) {
  const col = collection(db, 'inventory');

  if (!force) {
    const existing = await getDocs(query(col, where('type', '==', 'allopathy')));
    if (!existing.empty) {
      return { skipped: true, count: existing.size };
    }
  } else {
    const existing = await getDocs(query(col, where('type', '==', 'allopathy')));
    await Promise.all(existing.docs.map(d => deleteDoc(d.ref)));
  }

  const CHUNK = 50;
  let inserted = 0;

  for (let i = 0; i < ALLOPATHY_MEDICINES.length; i += CHUNK) {
    const chunk = ALLOPATHY_MEDICINES.slice(i, i + CHUNK);
    await Promise.all(chunk.map(([drugCode, name, unitSize, price]) =>
      addDoc(col, {
        medicineName: name,
        type: 'allopathy',
        drugCode,
        unitSize,
        price,
        formulation: getFormulation(name),
        category: getCategory(name),
        sideEffects: getSideEffects(name),
        stockQuantity: 0,
        indications: [],
        dose: '',
        precautions: '',
        createdAt: serverTimestamp(),
      })
    ));
    inserted += chunk.length;
  }

  return { inserted };
}
